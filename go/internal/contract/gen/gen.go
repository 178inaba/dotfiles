// Package gen writes the part of a contract that reflection cannot see.
//
// A library rather than the command itself, so that its own tests run and the
// lint step reads it. The command is contract/generate.go, which is excluded
// from the build: importing this package from the contract package would put
// go/parser in the ccx binary, and the only other importer is a test.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
)

// modulePath is the prefix the renderer looks fields up by.
const modulePath = "github.com/178inaba/dotfiles/go"

// sources are the packages whose types reach a contract. ghapi is here for
// one thing: issue.PR.State is a ghapi.PRState, and leaving it out renders the
// state of a sub-issue's pull request with no value set.
var sources = []string{
	"internal/issue",
	"internal/worktree",
	"internal/pullrequest",
	"internal/reviewprs",
	"internal/skill",
	"internal/ghapi",
}

// OutputFile is written beside the contract package, which is where go
// generate runs the command.
const OutputFile = "docs_gen.go"

// Write puts the table beside the contract package.
func Write(contractDir string) error {
	out, err := Generate(contractDir)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(contractDir, OutputFile), out, 0o644)
}

// Generate is Write without the write, so a test can ask whether the file on
// disk is what this would produce.
func Generate(contractDir string) ([]byte, error) {
	// internal/contract is two levels below the module root.
	moduleRoot := filepath.Join(contractDir, "..", "..")
	pkgs := make([]pkg, 0, len(sources))
	for _, s := range sources {
		pkgs = append(pkgs, pkg{path: modulePath + "/" + s, dir: filepath.Join(moduleRoot, s)})
	}

	d, err := extract(pkgs)
	if err != nil {
		return nil, err
	}
	return render(d)
}

func render(d docs) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run generate.go; DO NOT EDIT.\n\npackage contract\n\n")

	b.WriteString("// genFields is every contract field's doc comment, flattened to one line.\nvar genFields = map[string]string{\n")
	for _, k := range slices.Sorted(maps.Keys(d.Fields)) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(d.Fields[k]))
	}
	b.WriteString("}\n\n")

	b.WriteString("// genTypes is every contract type's own doc comment, flattened to one line.\nvar genTypes = map[string]string{\n")
	for _, k := range slices.Sorted(maps.Keys(d.Types)) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(d.Types[k]))
	}
	b.WriteString("}\n\n")

	b.WriteString("// genEnums is every named string type's constants, in declaration order.\nvar genEnums = map[string][]string{\n")
	for _, k := range slices.Sorted(maps.Keys(d.Enums)) {
		fmt.Fprintf(&b, "\t%s: {", strconv.Quote(k))
		for i, v := range d.Enums[k] {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(v))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// genPackages is every package the table was read from.\nvar genPackages = []string{\n")
	for _, p := range d.Packages {
		fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(p))
	}
	b.WriteString("}\n\n")

	b.WriteString("// genEnumDocs is what each of those constants means.\nvar genEnumDocs = map[string]string{\n")
	for _, k := range slices.Sorted(maps.Keys(d.EnumDocs)) {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(d.EnumDocs[k]))
	}
	b.WriteString("}\n")

	// Through go/format, or the lint step fails on the result.
	return format.Source(b.Bytes())
}
